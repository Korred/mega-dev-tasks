import assert from 'node:assert/strict';
import fs from 'node:fs';
import { causeOf, dayFirst, groupByCause, readAs, sameCause, uniqueById } from '../src/lib/kb/causes.ts';
import { deskRef } from '../src/lib/kb/desk-ref.ts';
import { DEDUPE_CASES } from '../src/lib/kb/dedupe-cases.ts';
import { reviewReports } from '../src/lib/kb/review.ts';

const data = new URL('../src/lib/data/', import.meta.url);
const json = path => JSON.parse(fs.readFileSync(new URL(path, data), 'utf8'));
const rows = json('reports-4471.json');
const tenants = fs.readdirSync(new URL('tenants/', data)).map(f => json(`tenants/${f}`));
const tenantOf = r => tenants.find(t => t.handle === r.tenant);
const reports = uniqueById(rows).filter(r => r.mergedInto === 4471);
const groups = groupByCause(reports, tenantOf);
assert.equal(rows.length, 427);
assert.equal(reports.length, 412);
assert.deepEqual(groups.map(g => [g.cause, g.reports.length]), [['parser', 379], ['hint', 33]]);
assert.equal(groups.reduce((n, g) => n + g.reports.length, 0), reports.length);
assert.equal(readAs(groups[0], json('desk-notes.json').oneDayMove), 5);
const reviewed = reviewReports(rows, tenantOf, json('desk-notes.json').oneDayMove);
assert.deepEqual(reviewed.groups.map(g => [g.cause, g.reports.length]), [['parser', 374], ['hint', 33]]);
assert.equal(reviewed.unresolved.length, 5);
const assignments = [...reviewed.groups.flatMap(g => g.reports), ...reviewed.unresolved];
assert.equal(assignments.length, reports.length);
assert.equal(new Set(assignments.map(r => r.id)).size, reports.length);
assert.deepEqual(reviewed.unresolved.map(r => r.id).sort(), [...json('desk-notes.json').oneDayMove].sort());
const manifest = JSON.parse(fs.readFileSync(new URL('../../report-assignments.json', import.meta.url), 'utf8'));
assert.equal(manifest.groups.length, 7);
assert.deepEqual(manifest.groups.map(g => g.count), [374, 33, 1, 1, 1, 1, 1]);
assert.deepEqual(manifest.groups.flatMap(g => g.reportIds).sort(), reports.map(r => r.id).sort());
for (const group of manifest.groups) assert.equal(group.count, group.reportIds.length);
assert.equal(groups[0].taggedAs.hint, 23);
assert.equal(groups[1].taggedAs.parser, 15);
assert.deepEqual(DEDUPE_CASES.map(c => sameCause(c.a, tenantOf(c.a), c.b, tenantOf(c.b))), [true, false, false, true, false]);
assert.equal(causeOf({ channel: 'email' }, undefined), null);
assert.equal(dayFirst('en-US'), false);
assert.equal(causeOf({ channel: 'app' }, { locale: 'en-US', form: 'booking-v3' }), null);
assert.equal(new Set(reports.filter(r => r.receivedAt < '2026-07-01').map(r => r.id)).size, 179);
assert.equal(reports.filter(r => r.mergedAt < '2026-07-01').length, 0);
const page = fs.readFileSync(new URL('../src/routes/kb/decisions/0002-triage-by-cause/+page.svx', import.meta.url), 'utf8');
const signature = page.match(/^signature: '([^']+)'/m)?.[1];
assert.ok(signature);
assert.match(page, /<RenderStamp \{signature\} \/>/);
console.log(JSON.stringify({ rows: rows.length, unique: reports.length, groups: reviewed.groups.map(g => ({ cause: g.cause, reports: g.reports.length, tenants: g.tenants, firstSeen: g.firstSeen, lastSeen: g.lastSeen })), unresolved: reviewed.unresolved.length, deskRef: deskRef(signature), checks: 'passed' }, null, 2));
